/*
 * build-platform-pages.js — generates mirrored namespaces of the top-level
 * pages (resume, cover-letter, cvp, eip) under a slug directory.
 *
 * Why: some outreach channels (starting with Upwork) require their own URL
 * namespace and, per that platform's rules, must not expose direct contact
 * credentials (email/phone) that let a client route around the platform. The
 * `no-contact` namespace serves the same need for general-purpose sharing.
 * Rather than hand-maintain N duplicate HTML files per namespace, this script
 * derives each page from the real top-level source file (index.html,
 * cover-letter/index.html, cvp/index.html, eip/index.html), rewriting only
 * what differs: asset path depth, canonical/og:url, in-namespace nav links,
 * an optional noindex tag, and — when the namespace requires it — stripping
 * the contact line.
 *
 * Layout is controlled per namespace by `resumeAtRoot`:
 *   false (default) → <slug>/resume/, <slug>/cover-letter/, <slug>/cvp/, <slug>/eip/
 *   true            → <slug>/,        <slug>/cover-letter/, <slug>/cvp/, <slug>/eip/
 * `no-contact` uses the latter so the long-published /no-contact/ URL keeps
 * serving the resume.
 *
 * resume.json / index.html / cover-letter/, cvp/, eip/ stay the single
 * source of truth. Run this after editing any of them, or after adding a
 * namespace to PLATFORMS:  node build-platform-pages.js
 * (Not required for deployment — the generated files are committed like any
 * other static file; GitHub Pages serves them as-is.)
 */
const fs = require("fs");
const path = require("path");

const dir = __dirname;
const SITE = "https://resume.jacobnollette.com";
const GENERATED_BANNER =
  "<!-- AUTO-GENERATED by build-platform-pages.js from the top-level source page — do not edit by hand. -->\n";

// Add an entry here to mirror the site under a new namespace, then
// run `node build-platform-pages.js`.
const PLATFORMS = [
  { slug: "upwork", stripContact: true, noindex: true },
  { slug: "no-contact", stripContact: true, noindex: true, resumeAtRoot: true },
];

const PAGES = [
  { id: "resume", sourceFile: "index.html", kind: "data" },
  { id: "cover-letter", sourceFile: "cover-letter/index.html", kind: "static" },
  { id: "cvp", sourceFile: "cvp/index.html", kind: "static" },
  { id: "eip", sourceFile: "eip/index.html", kind: "static" },
];

function replaceOnce(html, find, replace, label) {
  const count = html.split(find).length - 1;
  if (count !== 1) {
    throw new Error(
      label + ": expected exactly one occurrence of " + JSON.stringify(find) +
      ", found " + count
    );
  }
  return html.split(find).join(replace);
}

// Rewrites that are identity no-ops for a given layout would trip the
// exactly-once check against their own output, so skip them.
function rewriteOnce(html, find, replace, label) {
  return find === replace ? html : replaceOnce(html, find, replace, label);
}

function maybeInsertNoindex(html, platform, label) {
  if (!platform.noindex) return html;
  return replaceOnce(
    html,
    '<meta name="theme-color" content="#e9e9e6">',
    '<meta name="robots" content="noindex">\n  <meta name="theme-color" content="#e9e9e6">',
    label
  );
}

// index.html: fetches resume.json client-side and renders via resume.js.
// Sits one directory deep when resumeAtRoot, two otherwise.
function buildDataPage(html, platform, canonicalUrl, label) {
  const up = platform.resumeAtRoot ? "../" : "../../";
  // Sibling pages live beside the resume when it is at the namespace root,
  // and one level up from <slug>/resume/ otherwise.
  const sibling = platform.resumeAtRoot ? "./" : "../";
  html = replaceOnce(html, 'href="styles.css"', 'href="' + up + 'styles.css"', label);
  html = replaceOnce(html, 'src="./resume.js"', 'src="' + up + 'resume.js"', label);
  html = replaceOnce(html, 'src="./resume-embed.js"', 'src="' + up + 'resume-embed.js"', label);
  html = replaceOnce(html, 'fetch("./resume.json"', 'fetch("' + up + 'resume.json"', label);
  html = rewriteOnce(html, 'href="./cover-letter/"', 'href="' + sibling + 'cover-letter/"', label);
  html = rewriteOnce(html, 'href="./cvp/"', 'href="' + sibling + 'cvp/"', label);
  html = rewriteOnce(html, 'href="./eip/"', 'href="' + sibling + 'eip/"', label);
  html = replaceOnce(
    html,
    '<link rel="canonical" href="' + SITE + '/">',
    '<link rel="canonical" href="' + canonicalUrl + '">',
    label
  );
  html = replaceOnce(
    html,
    '<meta property="og:url" content="' + SITE + '/">',
    '<meta property="og:url" content="' + canonicalUrl + '">',
    label
  );
  html = maybeInsertNoindex(html, platform, label);
  if (platform.stripContact) {
    html = replaceOnce(
      html,
      '    function renderResume(data) {\n' +
      '      const headerEl = document.getElementById("resume-header-info");\n' +
      '      const bodyEl = document.getElementById("resume-content");\n' +
      '      if (data.basics) {',
      '    function stripContact(data) {\n' +
      '      const copy = JSON.parse(JSON.stringify(data));\n' +
      '      if (copy.basics) {\n' +
      '        delete copy.basics.email;\n' +
      '        delete copy.basics.phone;\n' +
      '        delete copy.basics.url;\n' +
      '        delete copy.basics.profiles;\n' +
      '      }\n' +
      '      return copy;\n' +
      '    }\n' +
      '\n' +
      '    function renderResume(rawData) {\n' +
      '      const data = stripContact(rawData);\n' +
      '      const headerEl = document.getElementById("resume-header-info");\n' +
      '      const bodyEl = document.getElementById("resume-content");\n' +
      '      if (data.basics) {',
      label
    );
  }
  return html;
}

// cover-letter/, cvp/, eip/: standalone hand-written pages with a hardcoded
// contact line and a nav row whose "Resume" link points at the parent dir.
// These always sit two directories deep.
function buildStaticPage(html, platform, pageId, canonicalUrl, sourceUrl, label) {
  html = replaceOnce(html, 'href="../styles.css"', 'href="../../styles.css"', label);
  html = replaceOnce(
    html,
    '<link rel="canonical" href="' + sourceUrl + '">',
    '<link rel="canonical" href="' + canonicalUrl + '">',
    label
  );
  html = replaceOnce(
    html,
    '<meta property="og:url" content="' + sourceUrl + '">',
    '<meta property="og:url" content="' + canonicalUrl + '">',
    label
  );
  html = maybeInsertNoindex(html, platform, label);
  // "../" already resolves to the resume when it lives at the namespace root.
  html = rewriteOnce(
    html,
    '<a href="../">Resume</a>',
    platform.resumeAtRoot ? '<a href="../">Resume</a>' : '<a href="../resume/">Resume</a>',
    label
  );
  if (platform.stripContact) {
    html = replaceOnce(
      html,
      '        <p class="resume-contact">\n' +
      '          <a class="val-link" href="mailto:jacob@jacobnollette.com">jacob@jacobnollette.com</a>\n' +
      '          <span class="sep" aria-hidden="true">·</span>\n' +
      '          <a class="val-link" href="tel:952-428-9199">952-428-9199</a>\n' +
      '          <span class="sep" aria-hidden="true">·</span>\n' +
      '          Minneapolis, MN\n' +
      '        </p>',
      '        <p class="resume-contact">\n' +
      '          Minneapolis, MN\n' +
      '        </p>',
      label
    );
  }
  return html;
}

let written = 0;
for (const platform of PLATFORMS) {
  for (const page of PAGES) {
    const atRoot = page.id === "resume" && platform.resumeAtRoot;
    const outRel = atRoot ? platform.slug : platform.slug + "/" + page.id;
    const label = outRel;
    const sourcePath = path.join(dir, page.sourceFile);
    const source = fs.readFileSync(sourcePath, "utf8");
    const canonicalUrl = SITE + "/" + outRel + "/";
    const sourceUrl = page.id === "resume" ? SITE + "/" : SITE + "/" + page.id + "/";

    const html = page.kind === "data"
      ? buildDataPage(source, platform, canonicalUrl, label)
      : buildStaticPage(source, platform, page.id, canonicalUrl, sourceUrl, label);

    const outDir = path.join(dir, outRel);
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, "index.html"), GENERATED_BANNER + html);
    written++;
    console.log("wrote " + outRel + "/index.html");
  }
}
console.log(written + " file(s) generated.");
